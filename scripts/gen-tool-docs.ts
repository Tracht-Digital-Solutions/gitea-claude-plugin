// Generates docs/TOOLS.md from the tool registry. `--check` fails if the file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
import * as z from 'zod/v4';
import { ALL_TOOLS } from '../src/tools/registry.js';

const MODULE_TITLES: Record<string, string> = {
  connection: 'Connection',
  repositories: 'Repositories and files',
  git: 'Branches, commits, tags and protection',
  issues: 'Issues, labels and milestones',
  projects: 'Projects (kanban boards)',
  time_tracking: 'Time tracking',
  pull_requests: 'Pull requests and reviews',
  organizations: 'Users, organisations, teams and access',
  actions: 'Gitea Actions',
  releases: 'Releases',
  packages: 'Packages',
  wiki: 'Wiki',
  extended: 'Webhooks, notifications and analysis',
};

const ACCESS_BADGE: Record<string, string> = {
  read: 'read',
  write: 'write',
  destructive: 'destructive',
  admin: 'admin',
};

const lines: string[] = [
  '# Tool reference',
  '',
  '<!-- Generated by `npm run docs:tools` from src/tools. Do not edit by hand. -->',
  '',
  `The MCP server provides **${ALL_TOOLS.length} tools**. Access levels: \`read\` (always on), \`write\` (on by default), \`destructive\` and \`admin\` (off by default, see [CONFIGURATION.md](CONFIGURATION.md)). Tools marked *confirm* need an explicit user confirmation for every call.`,
  '',
  'Most repository tools take optional `owner` and `repo`; when omitted they are taken from the git remote of the current working directory that points to the configured Gitea server. Every tool accepts an optional `profile`.',
  '',
];

for (const [module, title] of Object.entries(MODULE_TITLES)) {
  const tools = ALL_TOOLS.filter((t) => t.module === module);
  if (!tools.length) continue;
  lines.push(`## ${title}`, '', '| Tool | Access | Description | Parameters |', '| --- | --- | --- | --- |');
  for (const t of tools) {
    const params = Object.keys(z.object(t.input).shape)
      .filter((p) => p !== 'profile' && p !== 'owner' && p !== 'repo')
      .map((p) => `\`${p}\``)
      .join(', ');
    const access = `${ACCESS_BADGE[t.access]}${t.confirm ? ', confirm' : ''}`;
    const desc = t.description.replace(/\|/g, '\\|').replace(/\n/g, ' ');
    lines.push(`| \`${t.name}\` | ${access} | ${desc} | ${params || '–'} |`);
  }
  lines.push('');
}
const unknown = ALL_TOOLS.filter((t) => !(t.module in MODULE_TITLES));
if (unknown.length) throw new Error(`modules without a title: ${unknown.map((t) => t.module).join(', ')}`);

const target = 'docs/TOOLS.md';
const out = await format(`${lines.join('\n').trimEnd()}\n`, {
  ...(await resolveConfig(target)),
  parser: 'markdown',
});
if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(target, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== out) {
    console.error(`${target} is out of date. Run npm run docs:tools.`);
    process.exit(1);
  }
  console.log(`${target} is up to date`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${ALL_TOOLS.length} tools)`);
}
